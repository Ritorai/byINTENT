// Bundles the TypeScript server code to plain ESM that Node 20 can run.
//   server/watcher.ts  -> server-dist/watcher.mjs   (standalone watcher process)
//   server/apiEntry.ts -> server-dist/api.mjs       (imported by server.mjs)
// node_modules stay external (pg, viem, express are regular dependencies).

import { build } from "esbuild";
import { mkdir, rm } from "node:fs/promises";

await rm("server-dist", { recursive: true, force: true });
await mkdir("server-dist", { recursive: true });

const common = {
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  packages: "external",
  sourcemap: false,
  logLevel: "info",
  banner: { js: "// generated by scripts/build-server.mjs — do not edit" },
};

await build({ ...common, entryPoints: ["server/watcher.ts"], outfile: "server-dist/watcher.mjs" });
await build({ ...common, entryPoints: ["server/apiEntry.ts"], outfile: "server-dist/api.mjs" });
